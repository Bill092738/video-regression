"""E17 analysis (docs/E17-plan.md): preference rates with a cluster bootstrap over viewers and clips.

    uv run python scripts/e17_analyze.py runs/e17/results/*.json   # -> runs/e17_tables.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

COMPARISONS = ("recipe", "learned_g", "bitrate")
N_BOOT = 10_000


def load(files) -> list[dict]:
    rows = []
    for f in files:
        rows += json.loads(Path(f).read_text())["results"]
    return rows


def excluded(rows: list[dict]) -> dict[str, str]:
    out = {}
    for v in sorted({r["viewer"] for r in rows}):
        mine = [r for r in rows if r["viewer"] == v]
        ctrl = [r for r in mine if r["comparison"] == "bitrate" and r["repeat_of"] is None]
        if ctrl and np.mean([not r["chose_treatment"] for r in ctrl]) < 0.5:
            out[v] = "prefers 16 Mbps over near-lossless in more than half of the control trials"
            continue
        first = {r["trial"]: r for r in mine if r["repeat_of"] is None}
        flips = sum(first[r["repeat_of"]]["chose_treatment"] != r["chose_treatment"] for r in mine
                    if r["repeat_of"] is not None and r["repeat_of"] in first)
        if flips >= 2:
            out[v] = f"inconsistent in {flips} of the repeated trials"
    return out


def boot(rows: list[dict], seed: int = 0) -> tuple[float, float, float]:
    """Preference rate for the treatment; cluster bootstrap over viewers and clips."""
    viewers = sorted({r["viewer"] for r in rows})
    clips = sorted({r["clip"] for r in rows})
    m = np.full((len(viewers), len(clips)), np.nan)
    for r in rows:
        m[viewers.index(r["viewer"]), clips.index(r["clip"])] = float(r["chose_treatment"])
    rng = np.random.default_rng(seed)
    est = []
    for _ in range(N_BOOT):
        sub = m[rng.integers(0, len(viewers), len(viewers))][:, rng.integers(0, len(clips), len(clips))]
        est.append(np.nanmean(sub))
    return float(np.nanmean(m)), float(np.nanquantile(est, 0.025)), float(np.nanquantile(est, 0.975))


def main(files) -> None:
    rows = load(files)
    ex = excluded(rows)
    kept = [r for r in rows if r["viewer"] not in ex and r["repeat_of"] is None]
    out = ["# E17 results (generated by scripts/e17_analyze.py)", "",
           f"Viewers: {len({r['viewer'] for r in rows})}, excluded: {len(ex)}.", ""]
    for v, why in ex.items():
        out.append(f"* excluded {v}: {why}")
    out += ["", "| comparison | trials | treatment preferred | 95 % CI (viewers × clips) | verdict |", "|---|---|---|---|---|"]
    for comp in COMPARISONS:
        sub = [r for r in kept if r["comparison"] == comp]
        if not sub:
            continue
        p, lo, hi = boot(sub)
        verdict = "preferred" if lo > 0.5 else "dispreferred" if hi < 0.5 else "no clear preference"
        out.append(f"| {comp} | {len(sub)} | {100 * p:.0f} % | [{100 * lo:.0f} %, {100 * hi:.0f} %] | {verdict} |")
    Path("runs/e17_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:])
