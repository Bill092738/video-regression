"""E11 (docs/E11-plan.md): common creator recipes as a baseline, and the recommended upload bitrate.

    uv run python scripts/e11.py run      # evaluate every recipe on every clip, with the judges (resumable)
    uv run python scripts/e11.py tables   # -> runs/e11_tables.md, docs/img/e11/e11.png

Black box: sim:ugc_strict. Same classes, splits, judges and bootstrap CIs as P1.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

from vreg import classify, content, metrics
from vreg.evaluate import evaluate
from vreg.optimize import cache_root
from vreg.platform import make_platform

RUNS = Path("runs")
OUT = RUNS / "e11" / "results.json"
YT_1440P_KBPS = 16_000  # YouTube's recommended SDR upload bitrate for 1440p at 24-30 fps
RECIPES = {
    "tier": ({"upscale": 2.0}, None),
    "r_default": ({"upscale": 2.0, "sharpen": 1.0, "sharpen_radius": 2.0}, None),
    "r_mild": ({"upscale": 2.0, "sharpen": 0.5, "sharpen_radius": 2.0}, None),
    "r_mild_16m": ({"upscale": 2.0, "sharpen": 0.5, "sharpen_radius": 2.0}, YT_1440P_KBPS),
    "tier_16m": ({"upscale": 2.0}, YT_1440P_KBPS),
}
LABEL = {"tier": "tier-only (CRF 10)", "r_default": "×2 + default unsharp 5×5 1.0", "r_mild": "×2 + mild unsharp 5×5 0.5",
         "r_mild_16m": "mild recipe at 16 Mbps", "tier_16m": "tier-only at 16 Mbps"}
COLS = ("composite", "ssimulacra2", "dists", "xpsnr")
JUDGES = ("ssimulacra2", "dists", "xpsnr")

_spec = importlib.util.spec_from_file_location("p1_tables", Path(__file__).with_name("p1_tables.py"))
p1 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(p1)
bootstrap, gains, fmt = p1.bootstrap, p1.gains, p1.fmt


def run() -> None:
    plat = make_platform("sim:ugc_strict")
    work = cache_root(plat)
    names = list(classify.load()["clips"])
    clips = content.ensure_clips(names, content.CLIPS_DIR)
    res = json.loads(OUT.read_text()) if OUT.exists() else {}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    for clip, src in clips.items():
        row = res.setdefault(clip, {})
        for rid, (params, kbps) in RECIPES.items():
            if rid in row and all(j in row[rid] for j in JUDGES):
                continue
            r = evaluate(clip, src, params, plat, work, judges=metrics.JUDGE_METRICS, upload_kbps=kbps)
            row[rid] = r.metrics | {"upload_kbps": r.upload_kbps}
        OUT.write_text(json.dumps(res, indent=2))
        print(f"[e11] {clip:22s} " + " ".join(f"{rid}={row[rid]['ssimulacra2']:.1f}" for rid in RECIPES), flush=True)


def tables() -> None:
    d = p1.Data()
    res = json.loads(OUT.read_text())
    conf = {rid: {c: r[rid] for c, r in res.items() if rid in r} for rid in RECIPES}
    theta = d.base["theta_class"]
    out = ["# E11 tables (generated by scripts/e11.py)", "",
           "Black box sim:ugc_strict. Positive = better; mean [95 % CI over clips]; bold = CI excludes 0.", ""]

    out += ["## Recipes vs tier-only (CRF 10), every tested clip per class", "",
            "| class | recipe | " + " | ".join(COLS) + " |", "|---" * (len(COLS) + 2) + "|"]
    summary = {}
    for k in ("A", "B", "D"):
        clips = d.clips(k, ("train", "dev", "confirm"))
        for rid in ("r_default", "r_mild", "r_mild_16m", "tier_16m"):
            sts = {m: bootstrap(gains(conf[rid], conf["tier"], clips, m)) for m in COLS}
            summary.setdefault(k, {})[rid] = sts
            out.append(f"| {k} ({len(clips)}) | {LABEL[rid]} | " + " | ".join(fmt(m, *sts[m]) for m in COLS) + " |")
    out.append("")

    out += ["## Q1: does tuning add? Class-tuned θ − recipe, dev + confirm clips (θ never saw them)", "",
            "| class | θ − recipe | " + " | ".join(COLS) + " | tuning adds? |", "|---" * (len(COLS) + 3) + "|"]
    adds = {}
    for k in ("A", "B", "D"):
        clips = d.clips(k, ("dev", "confirm"))
        for rid in ("r_default", "r_mild"):
            sts = {m: bootstrap(gains(theta, conf[rid], clips, m)) for m in COLS}
            up = sum(sts[m][1] > 0 for m in JUDGES)
            down = sum(sts[m][2] < 0 for m in JUDGES)
            adds[(k, rid)] = up >= 2 and down == 0
            out.append(f"| {k} ({len(clips)}) | θ − {LABEL[rid]} | " + " | ".join(fmt(m, *sts[m]) for m in COLS)
                       + f" | {'yes' if adds[(k, rid)] else 'no'} ({up} up, {down} down) |")
    out.append("")
    for k in ("A", "B", "D"):
        p = load_theta(k)
        if p:
            out.append(f"* class {k} θ: unsharp {p['sharpen']:.2f}, size {2 * int(p['sharpen_radius']) + 1}")
    out.append("")

    out += ["## Q2: the recommended upload bitrate (16 Mbps) vs near-lossless (CRF 10), every tested clip", "",
            "| class | comparison | " + " | ".join(COLS) + " | median upload Mbps |", "|---" * (len(COLS) + 3) + "|"]
    for k in ("A", "B", "D"):
        clips = d.clips(k, ("train", "dev", "confirm"))
        for hi, lo in (("tier", "tier_16m"), ("r_mild", "r_mild_16m")):
            sts = [fmt(m, *bootstrap(gains(conf[lo], conf[hi], clips, m))) for m in COLS]
            mb = (np.median([conf[hi][c]["upload_kbps"] for c in clips]) / 1000,
                  np.median([conf[lo][c]["upload_kbps"] for c in clips]) / 1000)
            out.append(f"| {k} ({len(clips)}) | {LABEL[lo]} − {LABEL[hi]} | " + " | ".join(sts)
                       + f" | {mb[0]:.0f} → {mb[1]:.0f} |")
    out.append("")

    # gate with a recipe on A: chosen on train + dev (most judges positive over tier), checked on confirm
    tv = d.clips("A", ("train", "dev"))
    score = {rid: (sum(bootstrap(gains(conf[rid], conf["tier"], tv, m))[0] > 0 for m in JUDGES),
                   np.mean(gains(conf[rid], conf["tier"], tv, "ssimulacra2")))
             for rid in ("r_default", "r_mild")}
    best = max(score, key=lambda r: score[r])
    gated = {c: (conf[best][c] if d.cls[c] == "A" else conf["tier"][c]) for c in d.clips("*", ("confirm",)) if c in conf[best]}
    out += [f"## Gate with a recipe (exploratory; confirm clips were used in P1)", "",
            f"Recipe for class A chosen on train + dev: **{LABEL[best]}** "
            f"({score[best][0]} judges positive over tier-only). Other classes tier-only.", "",
            "| class | SSIMULACRA2 gate − tier | XPSNR gate − tier |", "|---|---|---|"]
    ok = True
    for k in ("A", "B", "D"):
        cl = d.clips(k, ("confirm",))
        s2, xp = (bootstrap(gains(gated, conf["tier"], cl, m)) for m in ("ssimulacra2", "xpsnr"))
        ok &= s2[0] >= 0 and xp[0] >= 0
        out.append(f"| {k} | {fmt('ssimulacra2', *s2)} | {fmt('xpsnr', *xp)} |")
    allc = list(gated)
    wins = [bootstrap(gains(gated, d.base["theta_global"], allc, m))[0] >= 0 for m in JUDGES]
    out += ["", "| judge | gate − P0 global sharpening-only θ | gate − P1 gate (class θ on A) |", "|---|---|---|"]
    p1gate = {c: (theta[c] if d.cls[c] == "A" else conf["tier"][c]) for c in allc if c in theta or d.cls[c] != "A"}
    for m in JUDGES:
        out.append(f"| {m} | {fmt(m, *bootstrap(gains(gated, d.base['theta_global'], allc, m)))} | "
                   f"{fmt(m, *bootstrap(gains(gated, p1gate, allc, m)))} |")
    out += ["", f"**Recipe gate: {'accepted' if ok and sum(wins) >= 2 else 'not accepted'}** by P1's criteria "
            f"(every class ≥ tier-only on SSIMULACRA2 and XPSNR: {'yes' if ok else 'no'}; ≥ global θ on {sum(wins)}/3).", ""]

    p1.bar_figure(summary, [(LABEL[r], r) for r in ("r_default", "r_mild", "r_mild_16m", "tier_16m")], JUDGES,
                  "E11: creator recipes vs tier-only (CRF 10), all tested clips (95 % CI)", Path("docs/img/e11/e11.png"))
    (RUNS / "e11_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


def load_theta(k: str) -> dict | None:
    res = p1.load(f"p1_sharp_{k}")
    return res["configs"]["best"] if res else None


if __name__ == "__main__":
    {"run": run, "tables": tables}[sys.argv[1] if len(sys.argv) > 1 else "tables"]()
