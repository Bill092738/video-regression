"""E7 tables and decision (docs/E7-plan.md), from the runs' rescore files.

    uv run python scripts/e7_tables.py              # -> runs/e7_tables.md, docs/img/e7/*.png
    uv run python scripts/e7_tables.py --decision   # prints fixes | helps | does-not-help | incomplete

Gains are signed so that positive = better; a clip's value is the mean over the seeds that have it;
CIs are 95 % bootstrap intervals over clips (10,000 resamples), as in P1.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

RUNS = Path("runs")
SEEDS = (0, 1, 2)
JUDGES = ("ssimulacra2", "dists", "xpsnr")
COLS = ("composite", "lpips", *JUDGES)

_spec = importlib.util.spec_from_file_location("p1_tables", Path(__file__).with_name("p1_tables.py"))
p1 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(p1)
bootstrap, gains, seed_gains, fmt, bar_figure = p1.bootstrap, p1.gains, p1.seed_gains, p1.fmt, p1.bar_figure

# configuration -> (run name pattern, rescore tags that hold its train and dev clips)
CONFIGS = {
    "P1 global G (emulator forward)": ("p1_g_lpips_s{s}", ("train", "p1")),
    "E7a: 6 real anchors": ("e7a_s{s}", ("e7",)),
    "E7b: 1 real anchor": ("e7b_s{s}", ("e7",)),
}


def g_rows(pattern: str, tags) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for s in SEEDS:
        rows = {}
        for t in tags:
            f = RUNS / pattern.format(s=s) / f"rescore_{t}.json"
            if f.exists():
                for c, r in json.loads(f.read_text())["clips"].items():
                    if "G_r0" in r:
                        rows[c] = r["G_r0"]
        for c, m in rows.items():
            out.setdefault(c, []).append(m)
    return out


def budget(pattern: str) -> dict:
    calls = []
    for s in SEEDS:
        f = RUNS / pattern.format(s=s) / "history.json"
        if f.exists():
            st = json.loads(f.read_text())["settings"]
            calls.append(st.get("blackbox_calls"))
    return calls[0] if calls else {}


def h1(g, theta, clips) -> tuple[bool, list[str]]:
    lines, passed = [], []
    for m in JUDGES:
        mean, lo, hi = bootstrap(gains(g, theta, clips, m))
        sg = seed_gains(g, theta, clips, m)
        if lo > 0:
            passed.append(sum(v > 0 for v in sg))
        lines.append(f"{m} {fmt(m, mean, lo, hi)} (positive seeds {sum(v > 0 for v in sg)}/{len(sg)})")
    s2 = np.mean(gains(g, theta, clips, "ssimulacra2") or [np.nan])
    ok = len(passed) >= 2 and s2 >= 0 and all(n >= 2 for n in passed)
    return ok, lines


def main() -> int:
    d = p1.Data()
    theta = d.base["theta_class"]
    a_dev, a_train = d.clips("A", ("dev",)), d.clips("A", ("train",))
    g = {name: g_rows(pat, tags) for name, (pat, tags) in CONFIGS.items()}
    complete = all(len(v) == len(SEEDS) for c in a_dev for v in [g["E7a: 6 real anchors"].get(c, [])])

    out = ["# E7 tables (generated by scripts/e7_tables.py)", "",
           "Platform sim:ugc_strict (the black box; no online platform). Same frozen emulator, clips, loss, "
           "trust region, steps and seeds for every row; only the estimator differs.", ""]
    for title, clips in (("class A dev (7 clips)", a_dev), ("class A train (13 clips; G's own training clips)", a_train)):
        out += [f"## G − class-tuned sharpening-only θ, {title}", "",
                "| configuration | seeds | " + " | ".join(COLS) + " |", "|---" * (len(COLS) + 2) + "|"]
        for name, rows in g.items():
            if not any(c in rows for c in clips):
                continue
            ns = max(len(rows[c]) for c in clips if c in rows)
            out.append(f"| {name} | {ns} | " + " | ".join(fmt(m, *bootstrap(gains(rows, theta, clips, m)))
                                                         for m in COLS) + " |")
        out.append("")

    p1g = g["P1 global G (emulator forward)"]
    out += ["## Paired: E7 − P1 global G (class A dev; same emulator and seeds)", "",
            "| configuration | " + " | ".join(COLS) + " | judges with CI above 0 |", "|---" * (len(COLS) + 2) + "|"]
    helps = {}
    for name in ("E7a: 6 real anchors", "E7b: 1 real anchor"):
        rows = g[name]
        if not any(c in rows for c in a_dev):
            continue
        ref = {c: {m: float(np.mean([r[m] for r in p1g[c]])) for m in COLS} for c in a_dev if c in p1g}
        sts = {m: bootstrap(gains(rows, ref, a_dev, m)) for m in COLS}
        helps[name] = sum(sts[m][1] > 0 for m in JUDGES)
        out.append(f"| {name} | " + " | ".join(fmt(m, *sts[m]) for m in COLS) + f" | {helps[name]}/3 |")
    out.append("")

    out += ["## Decision (docs/E7-plan.md)", ""]
    decision = "incomplete"
    if g["E7a: 6 real anchors"] and complete:
        fixed, lines = h1(g["E7a: 6 real anchors"], theta, a_dev)
        out += ["E7a vs class-tuned θ on A dev, H1 criteria: " + "; ".join(lines), ""]
        decision = "fixes" if fixed else "helps" if helps.get("E7a: 6 real anchors", 0) >= 2 else "does-not-help"
        consequence = {"fixes": "E9 is worth running with the E7 estimator; E7a is evaluated once on A confirm.",
                       "helps": "E9 is worth one overnight run with the E7 estimator.",
                       "does-not-help": "E9 is not run; the learned-G line stops at a negative result."}[decision]
        out += [f"**Decision: {decision}.** {consequence}", ""]
    else:
        out += ["(E7a not complete on the A dev clips yet)", ""]

    out += ["## Budget in black-box calls (clip-level platform calls)", "",
            "| configuration | training (anchors) | validation per run |", "|---|---|---|"]
    for name, (pat, _) in CONFIGS.items():
        b = budget(pat)
        if b:
            out.append(f"| {name} | {b['anchors']} | {b['validation']} |")
    out += ["| P1 global G | 0 (forward from the emulator only) | 45 |",
            "| emulator E (shared by every row) | 156 (26 clips × 6 variants) | – |",
            "| class-tuned θ for A | 195 (15 trials × 13 clips) | – |", ""]

    summary = {}
    for name, rows in g.items():
        for k in ("A", "B", "D"):
            clips = d.clips(k, ("dev",))
            if any(c in rows for c in clips):
                summary.setdefault(k, {})[name] = {m: bootstrap(gains(rows, theta, clips, m)) for m in JUDGES}
    bar_figure(summary, [(n, n) for n in CONFIGS], JUDGES,
               "E7: G − class-tuned sharpening-only θ, dev clips (95 % CI)", Path("docs/img/e7/e7_dev.png"))

    if "--decision" in sys.argv:
        print(decision)
        return 0
    (RUNS / "e7_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
