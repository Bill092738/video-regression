"""E10 (docs/E10-plan.md, reframed): how many clips does a per-platform validation of a recipe need?

    uv run python scripts/e10.py      # -> runs/e10_tables.md, docs/img/e10/e10.png

Inputs: E11's per-clip results on sim:ugc_strict (runs/e11/results.json) and sim:ugc_av1
(runs/e11/results_ugc_av1.json). The decision validated is "switch the recipe on iff its mean gain
over tier-only is >= 0 on both SSIMULACRA2 and XPSNR"; the truth is that rule on all of a class's
clips. Subsets are drawn without replacement, 10,000 per size.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from vreg import classify, features  # noqa: E402

RUNS = Path("runs")
SIZES = (2, 3, 4, 6, 8, 10, 12, 16)
DRAWS = 10_000
PLATFORMS = {"ugc_strict": RUNS / "e11" / "results.json", "ugc_av1": RUNS / "e11" / "results_ugc_av1.json"}
RECIPES = {"r_mild": "mild unsharp 5×5 0.5", "r_default": "default unsharp 5×5 1.0"}
CLASSES = ("A", "B", "D")
STRATEGIES = ("random", "hard-half")


def gains(res: dict, clips: list[str], rid: str) -> np.ndarray:
    """(n_clips, 2): SSIMULACRA2 and XPSNR gain of the recipe over tier-only."""
    return np.array([[res[c][rid]["ssimulacra2"] - res[c]["tier"]["ssimulacra2"],
                      res[c][rid]["xpsnr"] - res[c]["tier"]["xpsnr"]] for c in clips])


def decide(g: np.ndarray) -> np.ndarray:
    """g: (..., n, 2) -> switch on iff both mean gains >= 0."""
    return (g.mean(axis=-2) >= 0).all(axis=-1)


def subsets(n_total: int, n: int, hard: np.ndarray | None, rng) -> np.ndarray:
    """(DRAWS, n) index sets; hard-half draws ceil(n/2) from the hard indices and the rest elsewhere."""
    if hard is None:
        return np.argsort(rng.random((DRAWS, n_total)), axis=1)[:, :n]
    soft = np.setdiff1d(np.arange(n_total), hard)
    kh = min(-(-n // 2), len(hard))
    ks = n - kh
    a = hard[np.argsort(rng.random((DRAWS, len(hard))), axis=1)[:, :kh]]
    b = soft[np.argsort(rng.random((DRAWS, len(soft))), axis=1)[:, :ks]]
    return np.concatenate([a, b], axis=1)


def main() -> None:
    cls = classify.load()["clips"]
    feats = features.read_csv(Path("docs/p1/features.csv"))
    rng = np.random.default_rng(0)
    out = ["# E10 tables (generated by scripts/e10.py)", "",
           "Decision: switch the recipe on iff its mean gain over tier-only on the validation clips is ≥ 0 on both "
           "SSIMULACRA2 and XPSNR. Truth: the same rule on all of the class's clips. Error = P(decision ≠ truth) over "
           f"{DRAWS:,} subsets per size; 'hard-half' takes ⌈n/2⌉ clips from the class's top third by SI.", ""]
    curves, mins = {}, []
    for plat, f in PLATFORMS.items():
        if not f.exists():
            out += [f"({plat}: {f} missing)", ""]
            continue
        res = json.loads(f.read_text())
        for k in CLASSES:
            clips = [c for c, v in cls.items() if v["class"] == k and c in res]
            si = np.array([feats[c]["si"] for c in clips])
            hard = np.argsort(-si)[: max(1, len(clips) // 3)]
            for rid in RECIPES:
                if not all(rid in res[c] for c in clips):
                    continue
                g = gains(res, clips, rid)
                truth = bool(decide(g))
                m = g.mean(axis=0)
                for strat in STRATEGIES:
                    errs, harm = [], []
                    for n in SIZES:
                        if n >= len(clips):
                            errs.append(np.nan)
                            harm.append(np.nan)
                            continue
                        idx = subsets(len(clips), n, hard if strat == "hard-half" else None, rng)
                        dec = decide(g[idx])
                        errs.append(float((dec != truth).mean()))
                        harm.append(float((dec & (not truth)).mean()))
                    curves[(plat, k, rid, strat)] = errs
                    n10 = next((n for n, e in zip(SIZES, errs) if e <= 0.10), None)
                    n05 = next((n for n, e in zip(SIZES, errs) if e <= 0.05), None)
                    mins.append((plat, k, rid, strat, truth, m, n10, n05, errs, harm))
    out += ["## Error rate by validation size", "",
            "| platform | class | recipe | truth (all clips) | mean gain SSIMULACRA2 / XPSNR | strategy | "
            + " | ".join(f"n={n}" for n in SIZES) + " | n for ≤ 10 % | n for ≤ 5 % |",
            "|---" * (8 + len(SIZES)) + "|"]
    for plat, k, rid, strat, truth, m, n10, n05, errs, _ in mins:
        out.append(f"| {plat} | {k} | {RECIPES[rid]} | {'on' if truth else 'off'} | {m[0]:+.2f} / {m[1]:+.2f} | {strat} | "
                   + " | ".join("–" if np.isnan(e) else f"{100 * e:.0f} %" for e in errs)
                   + f" | {n10 or '> 16'} | {n05 or '> 16'} |")
    out += ["", "## Upload budget implied (2 uploads per validation clip: tier-only and recipe)", "",
            "| platform | class | recipe | strategy | uploads for ≤ 10 % error | uploads for ≤ 5 % error |", "|---|---|---|---|---|---|"]
    for plat, k, rid, strat, truth, m, n10, n05, errs, _ in mins:
        out.append(f"| {plat} | {k} | {RECIPES[rid]} | {strat} | {2 * n10 if n10 else '> 32'} | {2 * n05 if n05 else '> 32'} |")
    out.append("")

    fig, axes = plt.subplots(1, len(CLASSES), figsize=(4.4 * len(CLASSES), 3.6), sharey=True)
    for ax, k in zip(axes, CLASSES):
        for (plat, kk, rid, strat), errs in curves.items():
            if kk != k or rid != "r_mild":
                continue
            ax.plot(SIZES, [100 * e for e in errs], marker="o", ls="-" if strat == "random" else "--",
                    label=f"{plat}, {strat}")
        ax.axhline(10, color="0.5", lw=0.8)
        ax.set_title(f"class {k}, mild unsharp")
        ax.set_xlabel("validation clips n")
    axes[0].set_ylabel("decision error %")
    axes[0].legend(fontsize=8)
    fig.suptitle("E10: how many clips decide 'switch the recipe on?' correctly")
    fig.tight_layout()
    Path("docs/img/e10").mkdir(parents=True, exist_ok=True)
    fig.savefig("docs/img/e10/e10.png", dpi=110)
    plt.close(fig)
    (RUNS / "e10_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
