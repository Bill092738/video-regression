"""E9 tables and decision (docs/E9-plan.md), from the runs' rescore files.

    uv run python scripts/e9_tables.py              # -> runs/e9_tables.md, docs/img/e9/e9_dev.png
    uv run python scripts/e9_tables.py --decision   # prints beats | adds | does-not-add | incomplete

Same conventions as P1 and E7: positive = better, a clip's value is its seed mean, 95 % bootstrap CIs
over clips.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import numpy as np

RUNS = Path("runs")
_spec = importlib.util.spec_from_file_location("e7_tables", Path(__file__).with_name("e7_tables.py"))
e7 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(e7)
p1 = e7.p1
JUDGES, COLS, SEEDS = e7.JUDGES, e7.COLS, e7.SEEDS
bootstrap, gains, fmt = e7.bootstrap, e7.gains, e7.fmt

CONFIGS = {
    "P1 global G": ("p1_g_lpips_s{s}", ("train", "p1")),
    "E7a (6 anchors)": ("e7a_s{s}", ("e7",)),
    "E9: G on top of θ_A (6 anchors)": ("e9_s{s}", ("e9", "confirm")),
}
E9 = "E9: G on top of θ_A (6 anchors)"


def decide(rows, theta, clips) -> tuple[str, list[str]]:
    beats, lines = e7.h1(rows, theta, clips)
    sts = {m: bootstrap(gains(rows, theta, clips, m)) for m in JUDGES}
    if beats:
        return "beats", lines
    no_worse = all(st[2] >= 0 for st in sts.values())  # no CI entirely below 0
    some_better = any(st[1] > 0 for st in sts.values())
    return ("adds" if no_worse and some_better else "does-not-add"), lines


def main() -> int:
    d = p1.Data()
    theta = d.base["theta_class"]
    g = {name: e7.g_rows(pat, tags) for name, (pat, tags) in CONFIGS.items()}
    rows = g[E9]
    a_dev = d.clips("A", ("dev",))
    complete = all(len(rows.get(c, [])) == len(SEEDS) for c in a_dev)

    out = ["# E9 tables (generated by scripts/e9_tables.py)", "",
           "Platform sim:ugc_strict (the black box; no online platform). E9's G sits in front of θ_A, so at "
           "G = identity it equals θ_A; G − θ_A is what G adds.", ""]
    for title, k, splits in (("class A dev", "A", ("dev",)), ("class A train (G's training clips)", "A", ("train",)),
                             ("class A confirm (run once, only after a 'beats' decision)", "A", ("confirm",)),
                             ("class B dev", "B", ("dev",)), ("class D dev", "D", ("dev",))):
        clips = d.clips(k, splits)
        present = {n: r for n, r in g.items() if any(c in r for c in clips)}
        if not present:
            continue
        out += [f"## G − class-tuned θ, {title} ({len(clips)} clips)", "",
                "| configuration | seeds | " + " | ".join(COLS) + " |", "|---" * (len(COLS) + 2) + "|"]
        for name, r in present.items():
            ns = max(len(r[c]) for c in clips if c in r)
            out.append(f"| {name} | {ns} | " + " | ".join(fmt(m, *bootstrap(gains(r, theta, clips, m))) for m in COLS)
                       + " |")
        out.append("")

    ref = {c: {m: float(np.mean([x[m] for x in g["E7a (6 anchors)"][c]])) for m in COLS}
           for c in a_dev if c in g["E7a (6 anchors)"]}
    if any(c in rows for c in a_dev) and ref:
        out += ["## Paired: E9 − E7a (class A dev)", "", "| " + " | ".join(COLS) + " |", "|---" * len(COLS) + "|",
                "| " + " | ".join(fmt(m, *bootstrap(gains(rows, ref, a_dev, m))) for m in COLS) + " |", ""]

    out += ["## Decision (docs/E9-plan.md)", ""]
    decision = "incomplete"
    if complete:
        decision, lines = decide(rows, theta, a_dev)
        out += ["E9 vs class-tuned θ on A dev, H1 criteria: " + "; ".join(lines), "", f"**Decision: {decision}.**", ""]
        conf = d.clips("A", ("confirm",))
        if any(c in rows for c in conf):
            cdec, clines = decide(rows, theta, conf)
            out += ["Confirm (run once): " + "; ".join(clines), "", f"**Confirm: {cdec}.**", ""]
    else:
        out += ["(E9 not complete on the A dev clips yet)", ""]
    b = e7.budget("e9_s{s}")
    if b:
        out += [f"Budget in black-box calls: emulator pairs {b.get('emulator_pairs')} (shared by the seeds), "
                f"anchors {b['anchors']} per seed, validation {b['validation']} per seed.", ""]

    summary = {}
    for name, r in g.items():
        for k in ("A", "B", "D"):
            clips = d.clips(k, ("dev",))
            if any(c in r for c in clips):
                summary.setdefault(k, {})[name] = {m: bootstrap(gains(r, theta, clips, m)) for m in JUDGES}
    p1.bar_figure(summary, [(n, n) for n in CONFIGS], JUDGES,
                  "E9: G − class-tuned sharpening-only θ, dev clips (95 % CI)", Path("docs/img/e9/e9_dev.png"))

    if "--decision" in sys.argv:
        print(decision)
        return 0
    (RUNS / "e9_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
